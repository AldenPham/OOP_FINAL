    private static void addRoomGroup() {
        System.out.println("--- Add room group / category ---");
        String id = nextAvailableId("RG", roomGroups.keySet());
        System.out.println("Generated room-group ID: " + id);
        String name = readNonBlank("Room-group name: ");
        roomType type = readEnum("Room type", roomType.values());
        double overstayFee = readNonNegativeDouble("Overstay fee per day: ");
        double capacityFee = readNonNegativeDouble("Fee per extra person over capacity: ");

        roomGroup group = new roomGroup(name, id, type,
                new feePolicy(overstayFee, capacityFee));
        roomGroups.put(id, group);
        System.out.println("Room group added successfully.");
    }

    private static void addUtility() {
        System.out.println("--- Add utility ---");
        String id = nextAvailableId("UT", utilities.keySet());
        System.out.println("Generated utility ID: " + id);
        String name = readNonBlank("Utility name: ");
        double price = readNonNegativeDouble("Price per use: ");
        utility item = new utility(name, id, price);
        utilities.put(id, item);

        if (roomGroups.isEmpty()) {
            System.out.println("Utility created. Add a room group first, then create/assign utilities.");
            return;
        }

        System.out.println("Assign this utility to room groups. It can be assigned to more than one.");
        boolean assignedAtLeastOne = false;
        while (readYesNo("Assign to a room group? (y/n): ")) {
            listRoomGroupsShort();
            String groupId = readNonBlank("Room-group ID (or blank to stop): ");
            roomGroup group = roomGroups.get(groupId);
            if (group == null) {
                System.out.println("Room group not found.");
                continue;
            }
            if (!group.getUtilities().contains(item)) {
                group.addUtility(item);
            }
            if (readYesNo("Is this utility free for this room group? (y/n): ")) {
                item.addFreeGroup(group);
            }
            assignedAtLeastOne = true;
        }
        System.out.println(assignedAtLeastOne
                ? "Utility created and assigned."
                : "Utility created; it has not been assigned to any room group.");
    }

    private static void listRoomGroupsShort() {
        if (roomGroups.isEmpty()) {
            System.out.println("No room groups yet.");
            return;
        }
        roomGroups.forEach((id, group) -> System.out.printf("%s | %s%n", id, group.getType()));
    }


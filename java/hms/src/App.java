    private static void previewBill() {
        System.out.println("--- Preview bill ---");
        RentalContract contract = promptContract();
        if (contract == null) return;
        if (contract.getCheckOutTime() == null) {
            System.out.println("The customer has not checked out, so the final bill is not ready.");
            return;
        }
        printBillBreakdown(contract);
    }

    private static double printBillBreakdown(RentalContract contract) {
        double roomFee = hotel.calculateRoomFee(contract);
        double overstayFee = hotel.calculateOverstayFee(contract);
        double utilityFee = hotel.calculateUtilityFee(contract);
        double capacityFee = hotel.calculateOverMaxCapacityFee(contract);
        double deposit = roomFee * 0.10;
        double total = roomFee + overstayFee + utilityFee + capacityFee - deposit;

        System.out.printf(Locale.US, "Room fee:                 %.2f%n", roomFee);
        System.out.printf(Locale.US, "Overstay fee:             %.2f%n", overstayFee);
        System.out.printf(Locale.US, "Utility fee:              %.2f%n", utilityFee);
        System.out.printf(Locale.US, "Over-capacity fee:        %.2f%n", capacityFee);
        System.out.printf(Locale.US, "Deposit deduction (10%%): -%.2f%n", deposit);
        System.out.println("----------------------------------------");
        System.out.printf(Locale.US, "TOTAL DUE:                %.2f%n", total);
        return total;
    }

    private static void createInvoice() {
        System.out.println("--- Create invoice ---");
        RentalContract contract = promptContract();
        if (contract == null) return;
        if (contract.getCheckOutTime() == null) {
            System.out.println("Customer must check out before creating an invoice.");
            return;
        }
        if (invoicedContractIds.contains(contract.getContractId())) {
            System.out.println("An invoice has already been recorded for this contract in this console session.");
            return;
        }
        System.out.printf("Contract customer: %s (%s)%n",
                contract.getCustomer().getName(), contract.getCustomer().getId());
        System.out.println("Choose payer:");
        customers.forEach((id, c) -> System.out.printf("%s | %s%n", id, c.getName()));
        String payerId = readNonBlank("Payer customer ID: ");
        Customer payer = customers.get(payerId);
        if (payer == null) {
            System.out.println("Payer not found.");
            return;
        }
        paymentType method = readEnum("Payment method", paymentType.values());

        String output = captureStdout(() -> hotel.createInvoice(contract, payer, method));
        System.out.print(output);
        if (!output.contains("Invoice{")) {
            System.out.println("Invoice was not created. See the message above.");
            return;
        }

        double total = hotel.calculateRoomFee(contract)
                + hotel.calculateOverstayFee(contract)
                + hotel.calculateUtilityFee(contract)
                + hotel.calculateOverMaxCapacityFee(contract)
                - hotel.calculateRoomFee(contract) * 0.10;
        invoiceRecords.add(new InvoiceRecord(contract.getContractId(), payer.getId(),
                contract.getRoom().getRoomType(), method, contract.getCheckOutTime(), total));
        invoicedContractIds.add(contract.getContractId());
        System.out.println("Invoice saved for reporting in this console session.");
    }

    private static String captureStdout(Runnable operation) {
        PrintStream original = System.out;
        ByteArrayOutputStream buffer = new ByteArrayOutputStream();
        try (PrintStream temporary = new PrintStream(buffer, true, StandardCharsets.UTF_8)) {
            System.setOut(temporary);
            operation.run();
        } finally {
            System.setOut(original);
        }
        return buffer.toString(StandardCharsets.UTF_8);
    }


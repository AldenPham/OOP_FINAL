    private static final Map<String, Room> rooms = new LinkedHashMap<>();
    private static final Map<String, roomGroup> roomGroups = new LinkedHashMap<>();
    private static final Map<String, utility> utilities = new LinkedHashMap<>();
    private static final List<String> contractIds = new ArrayList<>();
    private static final List<InvoiceRecord> invoiceRecords = new ArrayList<>();

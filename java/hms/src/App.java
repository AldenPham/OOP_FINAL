    private static int nextContractNumber = 0;

    private static final class InvoiceRecord {
        private final String contractId;
        private final String customerId;
        private final roomType type;
        private final paymentType paymentMethod;
        private final LocalDateTime checkOutTime;
        private final double total;

        private InvoiceRecord(String contractId, String customerId, roomType type,
                              paymentType paymentMethod, LocalDateTime checkOutTime,
                              double total) {
            this.contractId = contractId;
            this.customerId = customerId;
            this.type = type;
            this.paymentMethod = paymentMethod;
            this.checkOutTime = checkOutTime;
            this.total = total;
        }
    }

    public static void main(String[] args) {
        System.out.println("==============================================");
        System.out.println("      HOTEL BOOKING SYSTEM - CONSOLE");
        System.out.println("==============================================");
        System.out.println("Date/time format: yyyy-MM-dd HH:mm (24-hour)");

        boolean running = true;
        while (running) {
            printMenu();
            int choice = readInt("Choose an option: ");
            System.out.println();

            try {
                switch (choice) {
                    case 1: addCustomer(); break;
                    case 2: listCustomers(); break;
                    case 3: addRoomGroup(); break;
                    case 4: addUtility(); break;
                    case 5: listRoomGroupsAndUtilities(); break;
                    case 6: addRoom(); break;
                    case 7: listRooms(false); break;
                    case 8: listRooms(true); break;
                    case 9: bookRoom(); break;
                    case 10: listContracts(); break;
                    case 11: findOngoingContracts(); break;
                    case 12: checkIn(); break;
                    case 13: useUtility(); break;
                    case 14: checkOut(); break;
                    case 15: previewBill(); break;
                    case 16: createInvoice(); break;
                    case 17: listInvoices(); break;
                    case 18: runReports(); break;
                    case 0:
                        running = false;
                        System.out.println("Goodbye!");
                        break;
                    default:
                        System.out.println("Invalid menu option. Choose 0-18.");
                }
            } catch (RuntimeException ex) {
                System.out.println("Operation failed: " + ex.getMessage());
            }

            if (running) {
                System.out.println();
                System.out.println("Press Enter to return to the menu...");
                INPUT.nextLine();
            }
        }
        INPUT.close();
    }


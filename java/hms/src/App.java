    private static List<RentalContract> allContracts() {
        return contractIds.stream()
                .map(hotel::findContractById)
                .filter(c -> c != null)
                .collect(Collectors.toList());
    }

    // 1. Types of rooms currently available.
    private static void reportAvailableRoomsByType() {
        System.out.println("\n1. Available rooms by room type");
        for (roomType type : roomType.values()) {
            long count = rooms.values().stream()
                    .filter(r -> r.getRoomStatus() == roomStatus.AVAILABLE)
                    .filter(r -> r.getRoomType() == type)
                    .count();
            System.out.printf("  %-12s : %d room(s)%n", type, count);
        }
    }

    // 2. Most booked room type, based on contracts created during this session.
    private static void reportMostBookedRoomType() {
        System.out.println("\n2. Most booked room type");
        Map<roomType, Long> counts = allContracts().stream().collect(Collectors.groupingBy(
                c -> c.getRoom().getRoomType(), Collectors.counting()));
        long max = java.util.Arrays.stream(roomType.values())
                .mapToLong(t -> counts.getOrDefault(t, 0L)).max().orElse(0L);
        if (max == 0) {
            System.out.println("  No bookings yet.");
            return;
        }
        java.util.Arrays.stream(roomType.values())
                .filter(t -> counts.getOrDefault(t, 0L) == max)
                .forEach(t -> System.out.printf("  %s : %d booking(s)%n", t, max));
    }

    // 3. The number of return visits is completed stays minus the first stay.
    private static void reportCustomerReturnVisits() {
        System.out.println("\n3. Number of customer return visits");
        Map<String, Long> completedStays = allContracts().stream()
                .filter(c -> c.getStatus() == contractStatus.completed)
                .collect(Collectors.groupingBy(c -> c.getCustomer().getId(), Collectors.counting()));
        boolean found = completedStays.values().stream().anyMatch(count -> count > 1);
        if (!found) {
            System.out.println("  No customer has returned for a second completed stay yet.");
            return;
        }
        completedStays.entrySet().stream()
                .filter(e -> e.getValue() > 1)
                .sorted(Map.Entry.<String, Long>comparingByValue().reversed())
                .forEach(e -> System.out.printf("  %s | completed stays: %d | return visits: %d%n",
                        e.getKey(), e.getValue(), e.getValue() - 1));
    }

    // 4. Revenue per payment method; based on successful invoice outputs.
    private static void reportRevenueByPaymentMethod() {
        System.out.println("\n4. Revenue by payment method");
        for (paymentType method : paymentType.values()) {
            double total = invoiceRecords.stream()
                    .filter(i -> i.paymentMethod == method)
                    .mapToDouble(i -> i.total).sum();
            System.out.printf(Locale.US, "  %-8s : %.2f%n", method, total);
        }
    }

    // 5. Utilities offered by each room group.
    private static void reportUtilitiesByRoomGroup() {
        System.out.println("\n5. Utilities by room group");
        if (roomGroups.isEmpty()) {
            System.out.println("  No room groups yet.");
            return;
        }
        roomGroups.forEach((id, group) -> {
            List<String> names = group.getUtilities().stream()
                    .map(u -> u.getUtilityName() + (u.isFreeForGroup(group) ? " (free)" : " (paid)"))
                    .collect(Collectors.toList());
            System.out.printf("  %s (%s): %s%n", id, group.getType(),
                    names.isEmpty() ? "no utilities" : String.join(", ", names));
        });
    }

    // 6. Least booked room type; room types with zero bookings are included.
    private static void reportLeastBookedRoomType() {
        System.out.println("\n6. Least booked room type");
        Map<roomType, Long> counts = allContracts().stream().collect(Collectors.groupingBy(
                c -> c.getRoom().getRoomType(), Collectors.counting()));
        long min = java.util.Arrays.stream(roomType.values())
                .mapToLong(t -> counts.getOrDefault(t, 0L)).min().orElse(0L);
        java.util.Arrays.stream(roomType.values())
                .filter(t -> counts.getOrDefault(t, 0L) == min)
                .forEach(t -> System.out.printf("  %s : %d booking(s)%n", t, min));
    }

    // 7. Contribution by room type uses the net invoice total.
    private static void reportRevenueByRoomType() {
        System.out.println("\n7. Revenue contributed by each room type");
        for (roomType type : roomType.values()) {
            double total = invoiceRecords.stream()
                    .filter(i -> i.type == type)
                    .mapToDouble(i -> i.total).sum();
            System.out.printf(Locale.US, "  %-12s : %.2f%n", type, total);
        }
    }

    // 8. Quarter is derived from the contract's checkout date because this model
    // does not store a separate invoice/payment timestamp.
    private static void reportRevenueByQuarter() {
        System.out.println("\n8. Revenue by quarter (based on check-out date)");
        if (invoiceRecords.isEmpty()) {
            System.out.println("  No invoices yet.");
            return;
        }
        Map<String, Double> byQuarter = invoiceRecords.stream().collect(Collectors.groupingBy(
                i -> i.checkOutTime.getYear() + "-Q" + (((i.checkOutTime.getMonthValue() - 1) / 3) + 1),
                java.util.TreeMap::new,
                Collectors.summingDouble(i -> i.total)));
        byQuarter.forEach((quarter, total) -> System.out.printf(Locale.US,
                "  %s : %.2f%n", quarter, total));
    }

    // 9. Total recorded invoice revenue.
    private static void reportTotalRevenue() {
        double total = invoiceRecords.stream().mapToDouble(i -> i.total).sum();
        System.out.println("\n9. Total hotel revenue (created invoices only)");
        System.out.printf(Locale.US, "  Total: %.2f%n", total);
    }

    // 10. Customer with the most completed stays; ties are all shown.
    private static void reportMostReturningCustomer() {
        System.out.println("\n10. Customer with the most return visits");
        Map<String, Long> completedStays = allContracts().stream()
                .filter(c -> c.getStatus() == contractStatus.completed)
                .collect(Collectors.groupingBy(c -> c.getCustomer().getId(), Collectors.counting()));
        long max = completedStays.values().stream().mapToLong(Long::longValue).max().orElse(0L);
        if (max <= 1) {
            System.out.println("  No returning customer found yet (a return requires at least 2 completed stays).");
            return;
        }
        completedStays.entrySet().stream()
                .filter(e -> e.getValue() == max)
                .forEach(e -> {
                    Customer c = customers.get(e.getKey());
                    System.out.printf("  %s (%s) | completed stays: %d | return visits: %d%n",
                            c == null ? e.getKey() : c.getName(), e.getKey(), max, max - 1);
                });
    }

    private static String readLine(String prompt) {
        System.out.print(prompt);
        return INPUT.nextLine().trim();
    }

    /**
     * Generates a unique ID for this in-memory console session.
     * IDs reset when the process restarts because the project currently has no database.
     */
    private static String nextAvailableId(String prefix, Set<String> existingIds) {
        int sequence = 1;
        String candidate;
        do {
            candidate = prefix + String.format(Locale.ROOT, "%03d", sequence++);
        } while (existingIds.contains(candidate));
        return candidate;
    }

    private static String readNonBlank(String prompt) {
        while (true) {
            String value = readLine(prompt);
            if (!value.isEmpty()) return value;
            System.out.println("Value cannot be blank.");
        }
    }

    private static int readInt(String prompt) {
        while (true) {
            try {
                return Integer.parseInt(readLine(prompt));
            } catch (NumberFormatException ex) {
                System.out.println("Please enter a whole number.");
            }
        }
    }

    private static int readPositiveInt(String prompt) {
        while (true) {
            int value = readInt(prompt);
            if (value > 0) return value;
            System.out.println("Value must be greater than zero.");
        }
    }

    private static double readNonNegativeDouble(String prompt) {
        while (true) {
            try {
                double value = Double.parseDouble(readLine(prompt));
                if (Double.isFinite(value) && value >= 0) return value;
            } catch (NumberFormatException ignored) {
                // Re-prompt below.
            }
            System.out.println("Please enter a valid number that is zero or greater.");
        }
    }

    private static boolean readYesNo(String prompt) {
        while (true) {
            String value = readLine(prompt).toLowerCase(Locale.ROOT);
            if (value.equals("y") || value.equals("yes")) return true;
            if (value.equals("n") || value.equals("no")) return false;
            System.out.println("Enter y or n.");
        }
    }

    private static LocalDateTime readDateTime(String prompt) {
        while (true) {
            String value = readNonBlank(prompt);
            try {
                return LocalDateTime.parse(value, DATE_TIME_FORMAT);
            } catch (DateTimeParseException ex) {
                System.out.println("Invalid date/time. Use format yyyy-MM-dd HH:mm, e.g. 2026-10-21 14:30.");
            }
        }
    }

    private static <E extends Enum<E>> E readEnum(String prompt, E[] values) {
        System.out.println(prompt + ":");
        for (int i = 0; i < values.length; i++) {
            System.out.printf("  %d. %s%n", i + 1, values[i]);
        }
        while (true) {
            int selected = readInt("Select number: ");
            if (selected >= 1 && selected <= values.length) return values[selected - 1];
            System.out.println("Choose a number from 1 to " + values.length + ".");
        }
    }
